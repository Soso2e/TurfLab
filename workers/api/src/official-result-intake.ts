import {
  hash, instant, num, obj, requireCondition, rows, str, type Row,
} from "../../../packages/shared/src/domain";
import { get, type Repository } from "../../../packages/shared/src/repository";
import { raceKey } from "../../../packages/shared/src/github-bridge";
import { saveResult, settle } from "./betting";

// The private GitHub file is user-controlled input, not independent proof of the
// linked official page. Strict structural validation is followed by Core's
// complete-entry, payout and revision checks before atomic durable commit.
export async function importOfficialResult(
  repo: Repository, input: Row, now: string,
): Promise<Row> {
  const doc = obj(input.document);
  requireCondition(doc.bridge_version === "1" &&
    doc.source_verification === "official_page_checked" &&
    doc.payouts_complete === true,
    "結果は公式公表/全払戻を照合した完全な入力が必要です");
  const result: Row = { ...obj(doc.result) };
  const race = await get(repo, "races", str(result, "race_id"));
  const date = str(race, "race_date_jst");
  requireCondition(doc.race_date_jst === date &&
    input.path === `results/${date}/${raceKey(str(race, "race_id"))}-official-v${num(result, "revision")}.json`,
    "公式結果のレース参照・日付・版・保存パスが不一致です");
  requireCondition(
    ["official", "cancelled"].includes(str(result, "official_status")),
    "確定していない結果は自動登録しません");
  requireCondition(instant(now) >= instant(race.scheduled_start_at),
    "発走前の結果を登録できません");
  const sourceUrl = str(result, "source_url");
  const checked = str(doc, "source_checked_at");
  const url = new URL(sourceUrl);
  requireCondition(url.protocol === "https:" && !url.username && !url.password,
    "公式結果には正しいHTTPS URLが必要です");
  requireCondition(race.jurisdiction === "JRA" || race.jurisdiction === "NAR",
    "登録済みレースの主催区分が未確認です。公式出馬表との照合が必要です");
  const hosts = race.jurisdiction === "JRA"
    ? ["jra.go.jp", "www.jra.go.jp", "app.jra.jp"]
    : ["keiba.go.jp", "www.keiba.go.jp"];
  requireCondition(hosts.includes(url.hostname),
    "公式結果URLと競馬管轄が一致しません");
  // The official page often shows no publication time. Then the source-check
  // time is a conservative upper bound (published no later than it was read):
  // it can only make the result look later, never leak it earlier. The basis
  // is stored so it is never mistaken for an observed publication time.
  const basis = doc.published_at_basis ?? "official";
  requireCondition(basis === "official" || basis === "retrieved_upper_bound",
    "公表時刻の根拠が不正です");
  if (basis === "official")
    requireCondition(result.published_at != null,
      "公式結果の公表時刻が未確認です。公式に表示が無い場合は published_at_basis:\"retrieved_upper_bound\" を指定してください");
  else {
    requireCondition(result.published_at == null,
      "取得時刻を上限とする場合、published_at は null にしてください（公表時刻を推測で埋めない）");
    result.published_at = checked;
    result.is_estimated = true;
    result.evidence_json = {
      ...obj(result.evidence_json ?? {}),
      published_at_basis: "retrieved_upper_bound",
    };
  }
  requireCondition(instant(checked) <= instant(now) &&
    instant(checked) >= instant(result.published_at),
    "結果公表前または未来の取得時刻は使えません");
  requireCondition(result.retrieved_at === checked && result.source_url === sourceUrl,
    "結果出典と取得時刻が不一致です");
  requireCondition(Array.isArray(doc.payouts) &&
    (doc.payouts.length > 0 || result.official_status === "cancelled"),
    "公式の全払戻データを確認してください");
  // Core verifies every registered entry's finish status, all ties, ticket
  // selections, full payout flag, sequential result revisions and idempotency.
  // Stable internal IDs are generated by Core, never guessed by ChatGPT.
  result.result_id ??= `result:auto:${race.race_id}:v${num(result, "revision")}`;
  const payouts = await Promise.all(rows(doc.payouts).map(async (p) => ({
    ...p,
    payout_id: p.payout_id ??
      `payout:auto:${await hash([result.result_id, p.ticket_type, p.selections_json])}`,
  })));
  const saved = await saveResult(repo, {
    result, payouts, payouts_complete: true,
  }, now);

  const raceEntries = (await repo.list("race_entries")).filter((e) => e.race_id === race.race_id);
  const positionMap = new Map<number, number>();
  let ahead = 0;
  for (const group of (Array.isArray(result.finish_order_json) ? result.finish_order_json : [])) {
    const tied = (Array.isArray(group) ? group : [group]).map(Number);
    for (const n of tied) positionMap.set(n, ahead + 1);
    ahead += tied.length;
  }
  const pace = obj(doc.pace_observation ?? {});
  for (const entry of raceEntries) {
    const horseNum = Number(entry.horse_number);
    const perfId = `performance:auto:${race.race_id}:${horseNum}`;
    const existing = await repo.get("performances", perfId);
    if (!existing) {
      const perf: Row = {
        schema_version: "0.2",
        created_at: now,
        valid_as_of: race.scheduled_start_at,
        source: "official_race_result",
        source_url: sourceUrl,
        is_estimated: false,
        performance_id: perfId,
        horse_id: entry.horse_id,
        race_id: race.race_id,
        jockey_id: entry.jockey_id,
        finish_position: positionMap.get(horseNum) ?? null,
        finish_time_s: null,
        last_3f_s: null,
        corner_positions_json: Array.isArray(pace.corners) ? pace.corners : [],
        draw_number: entry.draw_number ?? null,
        horse_number: horseNum,
        carried_weight_kg: entry.carried_weight_kg ?? null,
        body_weight_kg: null,
        body_weight_change_kg: null,
        going: null,
        margin: null,
        pace_observed: Array.isArray(pace.laps_s) && pace.laps_s.length ? pace.laps_s.join(",") : null,
        running_style_observed: null,
        trouble_notes: null,
      };
      await repo.put("performances", perf);
    }
  }

  const entries = await settle(repo, str(saved, "result_id"), now);
  return {
    status: "complete",
    race_id: race.race_id,
    result_id: saved.result_id,
    revision: saved.revision,
    virtual_bets_settled: entries.length,
    source_url: sourceUrl,
    source_checked_at: checked,
    published_at: saved.published_at,
    published_at_basis: basis,
    source_independently_fetched_by_core: false,
    note: "GitHub内の公式確認記録とCoreの完全性検証で保存。出典ページの本文はCoreから独立取得していません。",
  };
}
