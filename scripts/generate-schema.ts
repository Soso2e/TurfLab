import { format } from "prettier";
import { writeFile } from "node:fs/promises";
import Ajv from "ajv";
import addFormats from "ajv-formats";
import standaloneCode from "ajv/dist/standalone/index.js";
import { importSchema } from "../packages/shared/src/import-schema";
const ajv = new Ajv({
  allErrors: true,
  strict: false,
  code: { source: true, esm: true },
});
addFormats(ajv);
const code = standaloneCode(ajv, ajv.compile(importSchema)).replace(
  /require\("ajv\/dist\/runtime\/ucs2length"\)\.default/g,
  "unicodeLength",
);
// Static ESM imports keep runtime code generation out of Workers.
const imports: string[] = [];
let i = 0;
const esm = code.replace(
  /require\("([^"]+)"\)/g,
  (_m: string, path: string) => {
    const name = `runtimeImport${i++}`;
    imports.push(`import * as ${name} from ${JSON.stringify(path + ".js")};`);
    return name;
  },
);
await writeFile(
  "workers/api/src/import-validator.js",
  "// Generated by npm run generate:schema. Do not edit.\n" +
    imports.join("\n") +
    "\nconst unicodeLength = (value) => [...value].length;\n" +
    esm +
    "\n",
);
await writeFile(
  "database/sheets/chatgpt-import.schema.json",
  await format(JSON.stringify(importSchema), { parser: "json" }),
);
